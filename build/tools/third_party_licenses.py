"""
Writes THIRD_PARTY_LICENSES.md: every Python package installed in the app's environment, every
JavaScript package bundled into the web UI, and the bundled OCR models and fonts, with licences.

    venv/bin/python build/tools/third_party_licenses.py        (Windows: venv\\Scripts\\python ...)
"""
import importlib.metadata as md
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Drivers installed only on servers that use those databases (not in the default environment)
OPTIONAL = [
    ("pymssql", "SQL Server driver (only if engine = sqlserver)", "LGPL-2.1", "https://github.com/pymssql/pymssql"),
    ("psycopg / psycopg-binary", "PostgreSQL driver (only if engine = postgresql)", "LGPL-3.0", "https://www.psycopg.org"),
    ("opencv-python-headless", "Used instead of opencv-python on Linux/Windows servers (no GUI libraries)", "Apache-2.0", "https://github.com/opencv/opencv-python"),
]
ASSETS = [
    ("PP-OCRv4 detection / recognition, PP-OCR mobile v2 classifier models", "Bundled in rapidocr-onnxruntime; trained by PaddleOCR", "Apache-2.0", "https://github.com/PaddlePaddle/PaddleOCR"),
    ("Plus Jakarta Sans font", "Bundled via @fontsource/plus-jakarta-sans", "OFL-1.1", "https://github.com/tokotype/PlusJakartaSans"),
    ("JetBrains Mono font", "Bundled via @fontsource/jetbrains-mono", "OFL-1.1", "https://github.com/JetBrains/JetBrainsMono"),
    ("PDFium", "Bundled in pypdfium2", "BSD-3-Clause / Apache-2.0", "https://pdfium.googlesource.com/pdfium/"),
    ("ONNX Runtime", "Bundled in onnxruntime", "MIT", "https://github.com/microsoft/onnxruntime"),
]


def python_packages():
    rows = []
    for d in md.distributions():
        m = d.metadata
        lic = m.get("License-Expression") or m.get("License") or ""
        classifiers = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License ::")]
        if not lic or len(lic) > 60 or lic.upper() == "UNKNOWN":
            lic = ", ".join(classifiers) or lic[:60] or "see package"
        url = m.get("Home-page") or next((u.split(",", 1)[1].strip() for u in (m.get_all("Project-URL") or []) if "," in u), "")
        rows.append((m["Name"], m["Version"], " ".join(lic.split()), url))
    return sorted(rows, key=lambda r: r[0].lower())


def js_packages():
    """Packages bundled into the built UI (production dependencies only)."""
    front = os.path.join(ROOT, "frontend")
    try:
        out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--parseable"], cwd=front,
                             capture_output=True, text=True, shell=os.name == "nt").stdout.splitlines()[1:]
    except FileNotFoundError:
        return []
    rows = []
    for path in sorted(set(out)):
        try:
            with open(os.path.join(path, "package.json"), encoding="utf-8") as f:
                j = json.load(f)
            lic = j.get("license") or j.get("licenses")
            rows.append((j["name"], j["version"], lic if isinstance(lic, str) else json.dumps(lic), j.get("homepage", "")))
        except (OSError, ValueError, KeyError):
            pass
    return rows


def table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    py, js = python_packages(), js_packages()
    text = f"""# Third-party licences

DocuPulse IDP is licensed under the MIT License (see LICENSE) and is built only from
open-source components. This list is generated by
`build/tools/third_party_licenses.py`; re-run it after changing dependencies.

All licences below are OSI-approved open-source licences (MIT, BSD, Apache-2.0, ISC, MPL-2.0,
PSF, LGPL) or, for fonts, the SIL Open Font License. LGPL components (ldap3, and the optional
pymssql / psycopg drivers) are used unmodified as separately installed libraries.

Not part of this software: the database server you connect to (SQLite is public domain;
PostgreSQL uses the PostgreSQL Licence; Microsoft SQL Server is licensed by Microsoft) and
identity services such as Okta or Active Directory.

## Bundled models, fonts and native libraries

{table(ASSETS, ["Component", "Where", "Licence", "Source"])}

## Python packages ({len(py)})

{table(py, ["Package", "Version", "Licence", "Home page"])}

## Optional Python packages

{table(OPTIONAL, ["Package", "Used for", "Licence", "Home page"])}

## JavaScript packages bundled in the web UI ({len(js)})

{table(js, ["Package", "Version", "Licence", "Home page"])}

Build-only tools (the Angular CLI and build system, TypeScript, esbuild and their
dependencies) are used to build the UI and are not shipped; they are MIT, Apache-2.0, ISC, BSD or
MPL-2.0 licensed. The Angular service worker (ngsw-worker.js, MIT) is copied into the build.
"""
    path = os.path.join(ROOT, "THIRD_PARTY_LICENSES.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Wrote {path}: {len(py)} Python and {len(js)} JavaScript packages")


if __name__ == "__main__":
    main()
